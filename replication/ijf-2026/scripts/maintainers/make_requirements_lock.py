"""Write environments/python/requirements.lock with exact versions and wheel hashes.

The input is the fully resolved set of `name==version` pins (resolve it once with
`pip download --python-version 3.12 --platform manylinux_2_28_x86_64 --only-binary=:all:`).
For every pin, the sha256 of each wheel usable on CPython 3.12 Linux (x86_64 and aarch64), or
of the pure-Python wheel, is read from PyPI, so `pip install --require-hashes` in the image
installs exactly these files and nothing else.

Usage (maintainers only; needs network):
    python make_requirements_lock.py resolved.txt > requirements.lock
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request

WANTED = re.compile(r"(cp312-cp312-.*manylinux.*(x86_64|aarch64)|py3-none-any|py2\.py3-none-any)\.whl$")


def main() -> int:
    pins = []
    for line in open(sys.argv[1], encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if line:
            name, _, version = line.partition("==")
            pins.append((name.strip(), version.strip()))
    print("# Python environment of the IJF replication image (CPython 3.12, Linux x86_64/aarch64).")
    print("# Generated by scripts/maintainers/make_requirements_lock.py; install with")
    print("#   pip install --no-deps --require-hashes -r requirements.lock")
    for name, version in sorted(pins, key=lambda p: p[0].lower()):
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json") as r:
            files = json.load(r)["urls"]
        hashes = sorted({f["digests"]["sha256"] for f in files
                         if f["packagetype"] == "bdist_wheel" and WANTED.search(f["filename"])})
        if not hashes:
            raise SystemExit(f"no CPython 3.12 Linux wheel for {name}=={version}")
        print(f"{name}=={version} \\")
        print(" \\\n".join(f"    --hash=sha256:{h}" for h in hashes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
