def julia_cmd(paths: Paths) -> list[str]:
    exe = os.environ.get("IJF_JULIA", "julia")
    return [exe, f"--project={paths.julia_project}", "--startup-file=no", "--color=no"]


def which(exe: str) -> str | None:
    return shutil.which(exe)


def run_logged(cmd: list[str], log: Path, cwd: Path | None = None, timeout: float | None = None,
               env: dict | None = None) -> tuple[int, float]:
    """Run a command, tee its output into `log`, and return (exit code, seconds).

    A command that cannot be started or that times out returns a non-zero code; it is never
    reported as success.
    """
    log.parent.mkdir(parents=True, exist_ok=True)
    start = time.monotonic()
    full_env = os.environ.copy()
    if env:
        full_env.update(env)
    with open(log, "w", encoding="utf-8") as f:
        f.write("$ " + " ".join(cmd) + "\n")
        f.flush()
        try:
            proc = subprocess.Popen(cmd, cwd=cwd, env=full_env, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                                    errors="replace")
        except OSError as exc:
            f.write(f"cannot start: {exc}\n")
            return 127, 0.0
        try:
            assert proc.stdout is not None
            for line in proc.stdout:
                f.write(line)
                if os.environ.get("IJF_VERBOSE"):
                    sys.stdout.write("    " + line)
            code = proc.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            proc.kill()
            f.write(f"\nTIMEOUT after {timeout} s\n")
            return 124, time.monotonic() - start
    return code, time.monotonic() - start


def tail(path: Path, n: int = 15) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    return "\n".join(lines[-n:])
