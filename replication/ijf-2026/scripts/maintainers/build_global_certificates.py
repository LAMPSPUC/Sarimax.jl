"""Inventory of the global-optimization evidence behind the manuscript, one row per SCIP record.

Reads every archived SCIP record (artifact bundle part 1, the ecc4878 copies in
results/historical/, the identified re-run in results/reruns/) and every manuscript value
that claims a global-optimization result without an archived source, and writes
reports/global_certificate_inventory.csv. No number in the output is typed here: each comes
from a record, or is recomputed from the recorded coefficients and the input series.

Recomputed column `primal_exact`: the objective at the coefficients SCIP reported, with the
residuals generated by the model recursion (the equality constraints then hold exactly). SCIP
reports the sum of squares of its own residual variables, which satisfy the constraints only
within its feasibility tolerance, so `primal_reported` can lie below the true minimum.

Classification (one per record):
  certified                    SCIP OPTIMAL with a zero-gap limit (limits/gap = 0, the default),
                               relative gap 0 recorded, and a log of the same run or the dual
                               bound in the record; or an unlogged re-run whose primal objective is
                               identical to such a record
  feasible with open gap       a recorded finite gap or dual bound that is not closed: TIME_LIMIT,
                               or OPTIMAL under limits/gap > 0
  improved feasible without certification
                               a feasible point whose objective is below the local solution by
                               more than the tolerance effect, without a closed zero gap
  insufficient evidence        anything else: no record, no log and conflicting records, or no gap

Usage:
  python build_global_certificates.py --bundle DIR [--pjme-daily FILE] [--out FILE]
DIR is an unpacked artifact bundle (part 1). FILE is the PJME daily series a battery run derives
(output/runs/battery_global_value/<id>/raw/battery-2026-07/energy/data/pjme_daily.csv); without
it the PJME rows have no recomputed objective.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

REPL = Path(__file__).resolve().parents[2]
RERUN = "results/reruns/full-all-limit1-2026-10-20"
ECC = "results/historical/battery-2026-07-ecc4878"
SOLVER = "raw/battery-2026-07/solver"
YEARLY = "raw/scip-ipopt-yearly-2026-07"

COLUMNS = [
    "instance", "manuscript_item", "run", "record", "log", "formulation", "lifting", "data", "T",
    "solver", "initialization", "bounds", "auxiliary_constraints", "time_limit_s", "gap_limit",
    "tolerances", "status", "primal_reported", "primal_exact", "dual_bound", "relative_gap",
    "local_objective", "local_excess_over_bound", "runtime_s", "nodes", "classification", "note",
]

DIRECT = "direct JuMP SSE model written by the runner (no package estimation API)"
NO_LIFT = "none (non-seasonal model: no product terms to lift)"
INIT = "eps_1 fixed at 0 (conditional on the first observation); no warm start"
BOUNDS_MA = "theta in [-1, 1]; c and eps free"
BOUNDS_ARMA = "phi, theta in [-1, 1]; c and eps free"
SCIP_DEFAULT_TOL = "SCIP defaults (limits/gap = 0, limits/absgap = 0, numerics/feastol = 1e-6); not recorded by the run"


def jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def series(path: Path) -> list[float]:
    with open(path, newline="", encoding="utf-8") as f:
        return [float(r["value"]) for r in csv.DictReader(f)]


def sse(y: list[float], c: float, phi: float, theta: float) -> float:
    eps, s = 0.0, 0.0
    for t in range(1, len(y)):
        eps = y[t] - c - phi * y[t - 1] - theta * eps
        s += eps * eps
    return s


def fmt(v) -> str:
    if v is None or v == "":
        return ""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return repr(v)
    return str(v)


def record_class(status: str, gap, logged: bool, bound_recorded: bool, gap_limit: float) -> str:
    if status == "OPTIMAL" and gap_limit == 0.0 and gap == 0.0 and (logged or bound_recorded):
        return "certified"
    if gap is not None and gap != "" and (status == "TIME_LIMIT" or (status == "OPTIMAL" and gap_limit > 0)):
        return "feasible with open gap"
    return "insufficient evidence"


def battery_rows(bundle: Path, pjme: Path | None) -> list[dict]:
    rows: list[dict] = []
    sim = series(bundle / "raw/battery-2026-07/validation/data/sim_arma.csv")
    data = {"sim_arma": sim}
    if pjme is not None:
        v = series(pjme)
        m = sum(v) / len(v)
        data["pjme_daily(scaled)"] = [(x - m) / 1000.0 for x in v]

    # MA(1) certificates (Section 5.6) and the scaling study
    cert = [
        ("archive 8ffc512", bundle / SOLVER / "scip_cert_results.jsonl", "", 300.0),
        ("archive ecc4878", REPL / ECC / "scip_cert_results.jsonl", f"bundle:{SOLVER}/refresh_scip.log", 300.0),
        ("re-run 2026-10-20", REPL / RERUN / "battery_solver_comparison" / SOLVER / "scip_cert_results.jsonl",
         f"{RERUN}/battery_solver_comparison/logs/run_solver_scip_cert.log", 300.0),
    ]
    logged_obj = {}
    for run, path, log, limit in cert:
        for r in jsonl(path):
            if run == "archive ecc4878":
                logged_obj[r["dataset"]] = r["obj_value"]
            rows.append(cert_row(r, run, path, log, limit, "Section 5.6 (MA(1), T = 8-40)"))
    scaling = bundle / SOLVER / "scip_scaling_results.jsonl"
    for r in jsonl(scaling):
        rows.append(cert_row(r, "archive 8ffc512 (= ecc4878)", scaling,
                             f"bundle:{SOLVER}/scip_scaling_run*.log", 600.0,
                             "not cited by the 2026-10-16 revision (scaling study, tab:solver_scaling of the July 2026 draft)"))
    for row in rows:   # an unlogged re-run inherits the logged certificate with the same optimum
        if row["run"] == "archive 8ffc512" and row["classification"] != "certified" \
                and row["status"] == "OPTIMAL" and row["relative_gap"] == 0.0 \
                and logged_obj.get(row["instance"]) == float(row["primal_reported"]):
            row["classification"] = "certified"
            row["note"] += "; no log of this run: inherits the logged ecc4878 record, whose objective is identical"

    # Table 7
    gv = [   # ecc4878 first: the unlogged 8ffc512 records are checked against its logged ones
        ("archive ecc4878", REPL / ECC / "global_value_results.jsonl", f"bundle:{SOLVER}/global_value_run.log"),
        ("archive 8ffc512", bundle / SOLVER / "global_value_results.jsonl", ""),
        ("re-run 2026-10-20", REPL / RERUN / "battery_global_value" / SOLVER / "global_value_results.jsonl",
         f"{RERUN}/battery_global_value/logs/run_solver_global_value.log"),
    ]
    logged = {}
    for run, path, log in gv:
        recs = jsonl(path)
        local = {r["dataset"]: r for r in recs if r["solver"] == "Ipopt"}
        for r in recs:
            if r["solver"] != "SCIP":
                continue
            name = r["dataset"].split(" ")[0]
            y = data.get(name)
            ytr = y[: r["n_train"]] if y else None
            exact = sse(ytr, r["c"], r.get("phi", 0.0), r["theta"]) if ytr and "c" in r else None
            lo = local.get(r["dataset"])
            lo_exact = sse(ytr, lo["c"], lo.get("phi", 0.0), lo["theta"]) if ytr and lo and "c" in lo else None
            bound = r.get("objective_bound")
            gap = r.get("relative_gap", r.get("rel_gap"))
            is_logged = bool(log)
            note = []
            if run == "archive ecc4878" and r["dataset"].startswith("pjme"):
                # the log of this commit shows the batch solve of this instance killed (signal 15,
                # then a segmentation fault inside SoPlex) with no result line
                is_logged = False
                note.append("no log of this record: the log of this commit shows the batch solve of this "
                            "instance terminated by signal 15 and a segmentation fault in SoPlex, and the "
                            "record's 601.8 s implies a time limit of about 600 s, not the script's 900 s")
            if run == "archive ecc4878" and is_logged:
                logged[r["dataset"]] = r["obj_value"]
            cls = record_class(r["termination"], gap, is_logged, bound is not None, 0.0)
            if run == "archive 8ffc512" and cls != "certified" and r["termination"] == "OPTIMAL" \
                    and gap == 0.0:
                if logged.get(r["dataset"]) == r["obj_value"]:
                    cls = "certified"
                    note.append("no log of this run: inherits the logged ecc4878 record, whose objective is identical")
                else:
                    note.append("no log of this run; the logged records of this instance (ecc4878 and the "
                                "2026-10-20 re-run) ended at their time limits")
            if exact is not None and lo_exact is not None:
                note.append(f"exact objective at SCIP's coefficients minus at Ipopt's: {exact - lo_exact:+.3e}")
            excess = ""
            ref_bound = bound if bound is not None else (r["obj_value"] if cls == "certified" else None)
            if ref_bound is not None and lo_exact is not None:
                excess = (lo_exact - ref_bound) / lo_exact
            spec = "ARMA(1,0,1)" if "phi" in r else "MA(1)"
            rows.append({
                "instance": r["dataset"], "manuscript_item": "Table 7 (tab:local_global_forecasts)",
                "run": run, "record": rel(path), "log": log or "none",
                "formulation": DIRECT, "lifting": NO_LIFT,
                "data": f"{name}[1:{r['n_train']}] ({'scaled as (x - mean)/1000' if name.startswith('pjme') else 'simulated, seed 1234'})",
                "T": r["n_train"], "solver": f"SCIP {r.get('solver_version', '8.0.0 (SCIP_jll 0.2.1+0; not recorded in the record)')}",
                "initialization": INIT, "bounds": BOUNDS_ARMA if spec != "MA(1)" else BOUNDS_MA,
                "auxiliary_constraints": "none (no innovation bounds)",
                "time_limit_s": 900.0 if not (run == "archive ecc4878" and r["dataset"].startswith("pjme")) else "about 600 (see note)",
                "gap_limit": 0.0, "tolerances": SCIP_DEFAULT_TOL, "status": r["termination"],
                "primal_reported": r["obj_value"], "primal_exact": exact, "dual_bound": bound,
                "relative_gap": gap, "local_objective": lo_exact if lo_exact is not None else (lo or {}).get("obj_value"),
                "local_excess_over_bound": excess, "runtime_s": r["runtime_s"], "nodes": r.get("node_count"),
                "classification": cls, "note": "; ".join(note),
            })
    return rows


def cert_row(r: dict, run: str, path: Path, log: str, limit: float, item: str) -> dict:
    bound = r.get("objective_bound")
    gap = r.get("relative_gap", r.get("rel_gap"))
    bf = r.get("brute_force_check")
    note = []
    if bf is not None:
        note.append(f"brute-force profile minimum {bf!r} (exact recursion on a (theta, c) grid with "
                    f"refinement, c in [-3, 3]); reported primal minus it: {r['obj_value'] - bf:+.3e}")
    cls = record_class(r["termination"], gap, bool(log), bound is not None, 0.0)
    return {
        "instance": r["dataset"], "manuscript_item": item, "run": run, "record": rel(path),
        "log": log or "none", "formulation": DIRECT, "lifting": NO_LIFT,
        "data": f"sim_arma[1:{r['dataset'].split('T=')[1]}] (simulated, seed 1234)",
        "T": int(r["dataset"].split("T=")[1]), "solver": f"SCIP {r.get('solver_version', '8.0.0 (not recorded in the record)')}",
        "initialization": INIT, "bounds": BOUNDS_MA, "auxiliary_constraints": "none",
        "time_limit_s": r.get("time_budget_s", limit), "gap_limit": 0.0, "tolerances": SCIP_DEFAULT_TOL,
        "status": r["termination"], "primal_reported": r["obj_value"], "primal_exact": "",
        "dual_bound": bound, "relative_gap": gap, "local_objective": bf,
        "local_excess_over_bound": (bf - bound) / bf if (bf is not None and bound is not None) else "",
        "runtime_s": r["runtime_s"], "nodes": r.get("node_count"), "classification": cls,
        "note": "; ".join(note),
    }


def yearly_rows(bundle: Path) -> list[dict]:
    rows = []
    for fname, run, constrained in (("scip_experiment_results.csv", "July 2026 yearly study, free run", False),
                                    ("scip_constr_results.csv", "July 2026 yearly study, constrained run", True)):
        path = bundle / YEARLY / fname
        with open(path, newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                rel_diff = float(r["sigma2_reldiff"])
                status = r["scip_status"]
                if status == "OPTIMAL" and rel_diff < -1e-6:
                    cls = "improved feasible without certification"
                elif status == "OPTIMAL":
                    cls = "feasible with open gap"
                else:
                    cls = "insufficient evidence"
                rows.append({
                    "instance": f"M4 yearly series {r['series']} ARIMA({r['p']},{r['d']},{r['q']})",
                    "manuscript_item": "not cited by the 2026-10-16 revision (summarized in the 2026-10-17 update)",
                    "run": run, "record": f"bundle:{YEARLY}/{fname}",
                    "log": f"bundle:{YEARLY}/{fname.replace('_results.csv', '_log.txt')} (every 10th series and a summary)",
                    "formulation": "package API: Sarimax.fit! with a SCIP optimizer (fixed orders from an Ipopt auto fit)",
                    "lifting": "none generated by the package (no seasonal terms)",
                    "data": f"M4 yearly series {r['series']} (training part)", "T": r["T"],
                    "solver": "SCIP (SCIP.jl; version not recorded)",
                    "initialization": "package default of July 2026 (not recorded)",
                    "bounds": ("reflection parameterization, stationary = invertible = true" if constrained
                               else "coefficient box, stationary = invertible = false"),
                    "auxiliary_constraints": "none", "time_limit_s": 600.0, "gap_limit": 0.01,
                    "tolerances": "limits/gap = 0.01; other SCIP settings default, not recorded",
                    "status": status, "primal_reported": r["sigma2_scip"], "primal_exact": "",
                    "dual_bound": "", "relative_gap": "", "local_objective": r["sigma2_ipopt"],
                    "local_excess_over_bound": "", "runtime_s": r.get("s_scip", ""), "nodes": "",
                    "classification": cls,
                    "note": (f"objective is the package's sigma2; SCIP relative to Ipopt {rel_diff:+.3e}; "
                             "OPTIMAL here means a relative gap below 1%, not a zero-gap certificate"),
                })
    probes = (
        ("scip_size_result.txt", "size probe", "ARIMA(1,1,1), simulated random walk with drift, Random.seed!(1)"),
        ("scip_gap_result.txt", "gap-limit probe", "SARIMA(2,1,2)(1,0,1)_12, simulated trend + seasonal + random walk, T = 469"),
    )
    for fname, label, model in probes:
        text = (bundle / YEARLY / fname).read_text(encoding="utf-8")
        head = text.splitlines()[0]
        for line in text.splitlines()[1:]:
            parts = [p.strip() for p in line.split("|")]
            if len(parts) < 4 or not re.match(r"^[0-9.]+$", parts[0]):
                continue
            gap_limit = float(parts[0]) if label == "gap-limit probe" else 0.01
            T = re.search(r"T=(\d+)", head).group(1) if label == "gap-limit probe" else parts[0]
            status = parts[2]
            what = f"limits/gap = {parts[0]}" if label == "gap-limit probe" else f"T = {parts[0]}"
            rows.append({
                "instance": f"SCIP {label}: {model}; {what}",
                "manuscript_item": "not cited by the 2026-10-16 revision", "run": f"July 2026 SCIP {label}",
                "record": f"bundle:{YEARLY}/{fname}", "log": "the record is the run's own summary",
                "formulation": "package API: Sarimax.fit! with a SCIP optimizer (additive form, coefficient box)",
                "lifting": "none generated by the package (additive form: no product terms)", "data": model, "T": T,
                "solver": "SCIP (version not recorded)", "initialization": "package default of July 2026 (not recorded)",
                "bounds": "coefficient box (stationary = false)", "auxiliary_constraints": "none",
                "time_limit_s": 900.0 if label == "gap-limit probe" else 300.0, "gap_limit": gap_limit,
                "tolerances": f"limits/gap = {gap_limit}; others not recorded", "status": status,
                "primal_reported": "", "primal_exact": "", "dual_bound": "", "relative_gap": "",
                "local_objective": "", "local_excess_over_bound": "", "runtime_s": parts[1].rstrip("s"),
                "nodes": "",
                "classification": "insufficient evidence" if status != "OPTIMAL" else "feasible with open gap",
                "note": "only the status, time and coefficients were written; no objective, bound or gap",
            })
    return rows


def awaiting_rows() -> list[dict]:
    rows = []
    with open(REPL / "results/manuscript/manuscript_values.csv", newline="", encoding="utf-8") as f:
        for m in csv.DictReader(f):
            if m["source_kind"] != "none" or m["item"] not in ("Table S5", "Section 5.6"):
                continue
            what = f"{m['row']} | {m['column']}" if m["item"] == "Table S5" else m["row"]
            rows.append({
                "instance": what, "manuscript_item": f"{m['item']} ({m['label']}): printed {m['printed']}",
                "run": "August 2026 certification batch", "record": "none archived", "log": "none archived",
                "formulation": ("external harness with the bilinear reformulation of Section 3.2 "
                                "(described in the coordination e-mail of 2026-08-21; not archived)"),
                "lifting": "added manually by the external harness; not generated by the package API",
                "data": "not archived", "T": "", "solver": "SCIP (version not recorded)",
                "initialization": "Ipopt incumbent, innovation bounds |eps_t| <= sqrt(f_Ipopt) (manuscript; not archived)",
                "bounds": "not archived", "auxiliary_constraints": "innovation bounds (manuscript; not archived)",
                "time_limit_s": "600 (e-mail; not archived)", "gap_limit": "", "tolerances": "not archived",
                "status": "", "primal_reported": "", "primal_exact": "", "dual_bound": "", "relative_gap": "",
                "local_objective": "", "local_excess_over_bound": "", "runtime_s": "", "nodes": "",
                "classification": "insufficient evidence",
                "note": "awaiting evidence: see reports/missing_global_artifacts.md",
            })
    return rows


def rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPL).as_posix()
    except ValueError:
        parts = path.as_posix().split("/raw/", 1)
        return "bundle:raw/" + parts[1] if len(parts) == 2 else path.as_posix()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", type=Path, required=True)
    ap.add_argument("--pjme-daily", type=Path)
    ap.add_argument("--out", type=Path, default=REPL / "reports" / "global_certificate_inventory.csv")
    a = ap.parse_args()
    rows = battery_rows(a.bundle, a.pjme_daily) + yearly_rows(a.bundle) + awaiting_rows()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, COLUMNS, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: fmt(r.get(k)) for k in COLUMNS})
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["classification"]] = counts.get(r["classification"], 0) + 1
    print(f"{len(rows)} rows -> {a.out}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
