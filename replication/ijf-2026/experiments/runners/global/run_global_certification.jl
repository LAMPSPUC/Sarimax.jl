# Global-optimization certificates: Table S5 and the certified instances of Section 5.6.
#
# Runner for the experiment of the August 2026 certification batch, whose harness was not
# archived. For each instance: the conditional least-squares problem the package estimates
# (pre-sample innovations fixed at zero, or free under `mode = "free"`), solved locally by Ipopt
# and then globally by SCIP with the formulation of Sections 3.2 and 5.6:
#   * the multiplicative products phi_i*Phi_k and theta_j*Theta_w lifted into auxiliary
#     variables a_ik and m_jw, tied by bilinear equalities;
#   * innovation bounds |eps_t| <= sqrt(f_Ipopt): every point with a sum of squares no larger than
#     the local one satisfies them, so the global optimum is not cut off;
#   * the Ipopt solution as SCIP's starting point.
# Ipopt solves the same lifted model, so local and global solutions are of one problem.
#
# Instances: a TOML file (experiments/configs/global_certification_instances.toml), one
# [[instance]] per problem: id, class, orders p q P Q, period s, length T, seed, the
# data-generating coefficients and mode. Records: $IJF_RUN_DIR/raw/global-certification/
# records.jsonl, one per instance, with Ipopt's solution, SCIP's termination and raw status,
# primal objective, dual bound, relative gap, time, nodes, SCIP's coefficients, the EXACT
# objective at SCIP's coefficients (residuals regenerated by the recursion, so the model
# equations hold exactly) and the classification.
#
# Usage: julia run_global_certification.jl INSTANCES.toml [--time-limit S] [--only ID,ID] [--limit N]
# IJF_JOBS worker processes (Distributed) solve whole instances in parallel; SCIP is
# single-threaded, so wall time is about the instances' total over the number of workers.

using Distributed
import TOML

function parse_args(args)
    o = Dict{String,Any}("file" => nothing, "time_limit" => 600.0, "only" => String[], "limit" => 0)
    i = 1
    while i <= length(args)
        a = args[i]
        if a == "--time-limit"
            o["time_limit"] = parse(Float64, args[i+1]); i += 2
        elseif a == "--only"
            o["only"] = split(args[i+1], ','); i += 2
        elseif a == "--limit"
            o["limit"] = parse(Int, args[i+1]); i += 2
        else
            o["file"] = a; i += 1
        end
    end
    isnothing(o["file"]) && error("usage: run_global_certification.jl INSTANCES.toml [--time-limit S] [--only IDS] [--limit N]")
    return o
end

const OPTS = parse_args(ARGS)
const RUN_DIR = let d = get(ENV, "IJF_RUN_DIR", "")
    isempty(d) && error("IJF_RUN_DIR is not set; run through ./reproduce.sh full --experiment global_certification")
    abspath(d)
end
const OUT_DIR = joinpath(RUN_DIR, "raw", "global-certification")
mkpath(OUT_DIR)

const NJOBS = clamp(parse(Int, get(ENV, "IJF_JOBS", "1")), 1, max(1, Sys.CPU_THREADS))

const INSTANCES = let all = TOML.parsefile(OPTS["file"])["instance"]
    sel = isempty(OPTS["only"]) ? all : [i for i in all if i["id"] in OPTS["only"]]
    OPTS["limit"] > 0 ? sel[1:min(end, OPTS["limit"])] : sel
end

if NJOBS > 1 && nprocs() == 1 && length(INSTANCES) > 1
    addprocs(min(NJOBS, length(INSTANCES));
             exeflags = `--project=$(dirname(Base.active_project())) --startup-file=no --color=no`)
end

# loaded before the definitions: the macros they use must exist when the block is expanded
@everywhere using JuMP, Ipopt, SCIP, Random, Statistics

@everywhere begin

    "(1 - sum a_i B^i)(1 - sum b_k B^sk) = 1 - sum c_j B^j (negate = true), or the MA form with +."
    function expand(a::Vector{Float64}, b::Vector{Float64}, s::Int; negate::Bool)
        n = length(a) + s * length(b)
        c = zeros(n)
        for i in eachindex(a); c[i] += a[i]; end
        for k in eachindex(b)
            c[s*k] += b[k]
            for i in eachindex(a)
                c[s*k+i] += (negate ? -1 : 1) * a[i] * b[k]
            end
        end
        return c
    end

    coefs(inst, key) = Float64.(get(inst, key, Float64[]))

    function simulate(inst)
        rng = MersenneTwister(inst["seed"])
        s, T = get(inst, "s", 1), inst["T"]
        ar = expand(coefs(inst, "phi"), coefs(inst, "Phi"), s; negate = true)
        ma = expand(coefs(inst, "theta"), coefs(inst, "Theta"), s; negate = false)
        c, σ = Float64(get(inst, "c", 0.0)), Float64(get(inst, "sigma", 1.0))
        burn = 200 + 10 * s
        n = T + burn
        e = σ .* randn(rng, n)
        y = zeros(n)
        for t in 1:n
            acc = c + e[t]
            for j in eachindex(ar); t > j && (acc += ar[j] * y[t-j]); end
            for j in eachindex(ma); t > j && (acc += ma[j] * e[t-j]); end
            y[t] = acc
        end
        return y[burn+1:end]
    end

    spec(inst) = (get(inst, "p", 0), get(inst, "q", 0), get(inst, "P", 0), get(inst, "Q", 0), get(inst, "s", 1))

    "The lifted conditional least-squares model (the same for Ipopt and SCIP)."
    function build(y, sp, optimizer; free::Bool, epsbound = nothing, prebound = nothing)
        p, q, P, Q, s = sp
        T = length(y)
        lb = p + s * P + 1
        nlag = q + s * Q
        m = Model(optimizer)
        @variable(m, c)
        @variable(m, -binomial(p, i) <= ϕ[i = 1:p] <= binomial(p, i))
        @variable(m, -binomial(q, j) <= θ[j = 1:q] <= binomial(q, j))
        @variable(m, -binomial(P, k) <= Φ[k = 1:P] <= binomial(P, k))
        @variable(m, -binomial(Q, w) <= Θ[w = 1:Q] <= binomial(Q, w))
        @variable(m, -binomial(p, i) * binomial(P, k) <= a[i = 1:p, k = 1:P] <= binomial(p, i) * binomial(P, k))
        @variable(m, -binomial(q, j) * binomial(Q, w) <= mm[j = 1:q, w = 1:Q] <= binomial(q, j) * binomial(Q, w))
        @constraint(m, [i = 1:p, k = 1:P], a[i, k] == ϕ[i] * Φ[k])
        @constraint(m, [j = 1:q, w = 1:Q], mm[j, w] == θ[j] * Θ[w])
        if isnothing(epsbound)
            @variable(m, ε[lb:T])
        else
            @variable(m, -epsbound <= ε[lb:T] <= epsbound)
        end
        if free && nlag > 0
            if isnothing(prebound)
                @variable(m, εpre[(lb-nlag):(lb-1)])
            else
                @variable(m, -prebound <= εpre[(lb-nlag):(lb-1)] <= prebound)
            end
        end
        E(t) = t >= lb ? ε[t] : ((free && nlag > 0 && t >= lb - nlag) ? m[:εpre][t] : 0.0)
        for t in lb:T
            @constraint(m, y[t] == c +
                sum(ϕ[i] * y[t-i] for i in 1:p; init = 0.0) +
                sum(Φ[k] * y[t-s*k] for k in 1:P; init = 0.0) -
                sum(a[i, k] * y[t-i-s*k] for i in 1:p, k in 1:P; init = 0.0) +
                ε[t] +
                sum(θ[j] * E(t - j) for j in 1:q; init = 0.0) +
                sum(Θ[w] * E(t - s * w) for w in 1:Q; init = 0.0) +
                sum(mm[j, w] * E(t - j - s * w) for j in 1:q, w in 1:Q; init = 0.0))
        end
        @objective(m, Min, sum(ε[t]^2 for t in lb:T))
        return m
    end

    "Values of every variable, keyed by the variable, for warm starts and records."
    snapshot(m) = Dict(v => value(v) for v in all_variables(m))

    function coefficients(m)
        g(sym) = haskey(m, sym) ? Float64[value(v) for v in m[sym]] : Float64[]
        return Dict("c" => value(m[:c]), "phi" => g(:ϕ), "theta" => g(:θ), "Phi" => g(:Φ), "Theta" => g(:Θ),
                    "presample" => haskey(m, :εpre) ? Dict(string(t) => value(m[:εpre][t]) for t in axes(m[:εpre], 1)) : Dict())
    end

    "Sum of squares with the residuals regenerated by the recursion at the given coefficients."
    function exact_sse(y, sp, co)
        p, q, P, Q, s = sp
        lb = p + s * P + 1
        ar = expand(co["phi"], co["Phi"], s; negate = true)
        ma = expand(co["theta"], co["Theta"], s; negate = false)
        pre = Dict(parse(Int, k) => v for (k, v) in co["presample"])
        e = Dict{Int,Float64}()
        E(t) = t >= lb ? e[t] : get(pre, t, 0.0)
        sse = 0.0
        for t in lb:length(y)
            pred = co["c"] + sum(ar[j] * y[t-j] for j in eachindex(ar); init = 0.0) +
                   sum(ma[j] * E(t - j) for j in eachindex(ma); init = 0.0)
            e[t] = y[t] - pred
            sse += e[t]^2
        end
        return sse
    end

    tryget(f) = try
        v = f()
        v isa Real && !isfinite(v) ? nothing : v
    catch
        nothing
    end

    function solve_instance(inst, time_limit)
        sp = spec(inst)
        free = get(inst, "mode", "zeroed") == "free"
        y = simulate(inst)
        rec = Dict{String,Any}("id" => inst["id"], "class" => inst["class"], "orders" => collect(sp),
                               "T" => inst["T"], "seed" => inst["seed"], "mode" => get(inst, "mode", "zeroed"),
                               "dgp" => Dict(k => inst[k] for k in ("phi", "theta", "Phi", "Theta", "c", "sigma") if haskey(inst, k)),
                               "time_limit_s" => time_limit)
        # ---- local: Ipopt on the lifted model, from zero ----------------------------------
        loc = build(y, sp, optimizer_with_attributes(Ipopt.Optimizer, "print_level" => 0); free = free)
        tl = @elapsed optimize!(loc)
        rec["ipopt_status"] = string(termination_status(loc))
        rec["ipopt_time_s"] = tl
        if !has_values(loc)
            rec["classification"] = "insufficient evidence"
            rec["note"] = "Ipopt returned no solution"
            return rec
        end
        f_local = objective_value(loc)
        co_local = coefficients(loc)
        rec["ipopt_objective"] = f_local
        rec["ipopt_coefficients"] = co_local
        rec["ipopt_exact_objective"] = exact_sse(y, sp, co_local)
        # ---- global: SCIP with innovation bounds and the Ipopt warm start -----------------
        bound = sqrt(f_local) * (1 + 1e-6)
        prebound = free ? 10 * std(y) : nothing
        rec["innovation_bound"] = bound
        rec["presample_bound"] = prebound
        glo = build(y, sp, optimizer_with_attributes(SCIP.Optimizer, "display/verblevel" => 0,
                                                     "limits/time" => time_limit);
                    free = free, epsbound = bound, prebound = prebound)
        start = snapshot(loc)
        warm = try
            for v in all_variables(glo)
                w = variable_by_name(loc, name(v))
                isnothing(w) || set_start_value(v, start[w])
            end
            true
        catch
            false
        end
        rec["warm_start"] = warm
        tg = @elapsed optimize!(glo)
        st = termination_status(glo)
        rec["scip_status"] = string(st)
        rec["scip_raw_status"] = tryget(() -> raw_status(glo))
        rec["scip_time_s"] = tg
        rec["scip_solve_time_s"] = tryget(() -> solve_time(glo))
        rec["scip_nodes"] = tryget(() -> node_count(glo))
        rec["scip_version"] = tryget(() -> MOI.get(glo, MOI.SolverVersion()))
        rec["dual_bound"] = tryget(() -> objective_bound(glo))
        rec["relative_gap"] = tryget(() -> relative_gap(glo))
        if has_values(glo)
            co = coefficients(glo)
            rec["scip_objective"] = objective_value(glo)
            rec["scip_coefficients"] = co
            rec["scip_exact_objective"] = exact_sse(y, sp, co)
        end
        db = rec["dual_bound"]
        rec["local_excess_over_bound"] = isnothing(db) ? nothing : (f_local - db) / f_local
        ex = get(rec, "scip_exact_objective", nothing)
        rec["improvement_over_local"] = isnothing(ex) ? nothing : (rec["ipopt_exact_objective"] - ex) / rec["ipopt_exact_objective"]
        improved = !isnothing(ex) && ex < rec["ipopt_exact_objective"] * (1 - 1e-6)
        rec["classification"] =
            st == MOI.OPTIMAL ? "certified" :
            improved ? "improved feasible without certification" :
            (!isnothing(db) && isfinite(db)) ? "feasible with open gap" : "insufficient evidence"
        return rec
    end
end

function jsonline(rec)
    # minimal JSON writer (no extra dependency on the workers' side)
    enc(x::Nothing) = "null"
    enc(x::Bool) = x ? "true" : "false"
    enc(x::Integer) = string(x)
    enc(x::AbstractFloat) = isfinite(x) ? repr(Float64(x)) : "null"
    enc(x::AbstractString) = "\"" * replace(x, "\\" => "\\\\", "\"" => "\\\"") * "\""
    enc(x::Symbol) = enc(String(x))
    enc(x::AbstractVector) = "[" * join(enc.(x), ",") * "]"
    enc(x::Tuple) = enc(collect(x))
    enc(x::AbstractDict) = "{" * join([enc(string(k)) * ":" * enc(v) for (k, v) in sort(collect(x); by = first)], ",") * "}"
    enc(x) = enc(string(x))
    return enc(rec)
end

println("global certification: $(length(INSTANCES)) instances, time limit $(OPTS["time_limit"]) s, $(nworkers()) worker(s)")
flush(stdout)
const RECORDS = joinpath(OUT_DIR, "records.jsonl")
isfile(RECORDS) && rm(RECORDS)
results = pmap(inst -> solve_instance(inst, OPTS["time_limit"]), INSTANCES; on_error = e -> e)
open(RECORDS, "w") do io
    for (inst, r) in zip(INSTANCES, results)
        if r isa Exception
            r = Dict{String,Any}("id" => inst["id"], "class" => inst["class"], "classification" => "insufficient evidence",
                                 "error" => sprint(showerror, r))
        end
        println(io, jsonline(r))
        println(rpad(r["id"], 28), " ", rpad(get(r, "scip_status", "-"), 12),
                " local ", get(r, "ipopt_objective", "-"), " bound ", get(r, "dual_bound", "-"),
                " gap ", get(r, "relative_gap", "-"), " ", round(get(r, "scip_time_s", 0.0); digits = 1), " s  ",
                r["classification"])
    end
end
println("global certification DONE -> ", RECORDS)
