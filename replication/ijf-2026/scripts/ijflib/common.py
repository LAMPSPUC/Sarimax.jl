EXIT_OK = 0
EXIT_FAIL = 1
EXIT_USAGE = 2
EXIT_ENV = 3
EXIT_INPUT = 4

PASS = "PASS"
FAIL = "FAIL"
MISSING = "MISSING"
SKIPPED = "SKIPPED"
WARN = "WARN"
INFO = "INFO"

# A run fails if any row has one of these statuses. SKIPPED and WARN never fail a run, but
# they are listed in every report so that nothing is silently left out.
FAILING = {FAIL, MISSING}


# ---------------------------------------------------------------------------------------------
# Locations
# ---------------------------------------------------------------------------------------------
@dataclass(frozen=True)
class Paths:
    repo: Path          # the Sarimax.jl checkout the code runs from
    repl: Path          # replication/ijf-2026 inside it
    artifacts: Path     # archived artifact bundle (read-only in the container)
    external: Path      # third-party input data: m4/, pjme/ (read-only in the container)
    output: Path        # everything generated by a reproduction run
    runtime: str        # "docker" or "native"

    @property
    def reports(self) -> Path:
        return self.output / "reports"

    @property
    def m4(self) -> Path:
        return self.external / "m4"

    @property
    def pjme(self) -> Path:
        return self.external / "pjme"

    @property
    def julia_project(self) -> Path:
        return self.repl / "environments" / "julia"


@dataclass(frozen=True)
class BundlePart:
    """One tarball of the archived artifact bundle (artifacts.lock). Every part extracts into
    the same directory; its files are listed, with their SHA-256, in its own inventory."""
    name: str
    version: str
    file: str                 # tarball name
    sha256: str               # SHA-256 of the tarball
    inventory: str            # inventory file in replication/ijf-2026, one line per file
    inventory_sha256: str     # SHA-256 of that inventory file (written into the marker)
    url: str
    doi: str
    marker: str               # file in the artifact directory written once the part verified


def bundle_parts(repl: Path) -> list[BundlePart]:
    """Part 1 is [bundle] (sarimax-ijf-2026-artifacts-v1, inventory artifacts.sha256); further
    parts are [[parts]] entries. The parts' files never overlap."""
    import tomllib
    lock = tomllib.loads((repl / "artifacts.lock").read_text(encoding="utf-8"))
    out = []
    for i, p in enumerate([lock["bundle"]] + list(lock.get("parts", []))):
        out.append(BundlePart(name=p["name"], version=str(p.get("version", "")), file=p["file"],
                              sha256=p.get("sha256", ""), inventory=p.get("inventory", "artifacts.sha256"),
                              inventory_sha256=p.get("inventory_sha256", ""), url=p.get("url", ""),
                              doi=p.get("doi", ""), marker=".complete" if i == 0 else f".complete-{p['name']}"))
    return out


def detect_paths() -> Paths:
    here = Path(__file__).resolve()
    repl = here.parents[2]                      # .../replication/ijf-2026
    repo = Path(os.environ.get("IJF_REPO_ROOT", repl.parents[1]))
    runtime = os.environ.get("IJF_RUNTIME", "native")
    if runtime == "docker":
        defaults = (Path("/ijf/artifacts"), Path("/ijf/data"), Path("/ijf/output"))
    else:
        defaults = (repl / "artifacts", repl / "data" / "external", repl / "output")
    return Paths(
        repo=repo,
        repl=repl,
        artifacts=Path(os.environ.get("IJF_ARTIFACTS_DIR", defaults[0])),
        external=Path(os.environ.get("IJF_DATA_DIR", defaults[1])),
        output=Path(os.environ.get("IJF_OUTPUT_DIR", defaults[2])),
        runtime=runtime,
    )


# ---------------------------------------------------------------------------------------------
# Hashing
# ---------------------------------------------------------------------------------------------
def sha256_file(path: Path, strip_cr: bool = False) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk.replace(b"\r", b"") if strip_cr else chunk)
    return h.hexdigest()


def read_sha256_list(path: Path) -> list[tuple[str, str]]:
    """Parse a `sha256sum`-style file into (hash, relative path) pairs."""
    pairs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, _, name = line.partition("  ")
        pairs.append((digest.strip().lower(), name.strip().lstrip("*")))
    return pairs


# ---------------------------------------------------------------------------------------------
# Reports
# ---------------------------------------------------------------------------------------------
def now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()


@dataclass
class Row:
    stage: str
    artifact: str
    expected: str = ""
    generated: str = ""
    difference: str = ""
    status: str = INFO
    note: str = ""


@dataclass
class Report:
    """A list of PASS/FAIL/MISSING/SKIPPED rows written as Markdown, CSV and JSON."""

    name: str
    paths: Paths
    rows: list[Row] = field(default_factory=list)
    started: str = field(default_factory=now_iso)

    def add(self, stage: str, artifact: str, status: str, expected="", generated="",
            difference="", note="") -> Row:
        row = Row(stage, artifact, _fmt(expected), _fmt(generated), _fmt(difference), status, note)
        self.rows.append(row)
        colour = {PASS: "\033[32m", FAIL: "\033[31m", MISSING: "\033[31m",
                  WARN: "\033[33m", SKIPPED: "\033[33m"}.get(status, "")
        reset = "\033[0m" if colour and sys.stdout.isatty() else ""
        colour = colour if sys.stdout.isatty() else ""
        detail = f" — {note}" if note else ""
        print(f"  [{colour}{status:7s}{reset}] {stage}: {artifact}{detail}", flush=True)
        return row

    @property
    def failed(self) -> bool:
        return any(r.status in FAILING for r in self.rows)

    def counts(self) -> dict[str, int]:
        out: dict[str, int] = {}
        for r in self.rows:
            out[r.status] = out.get(r.status, 0) + 1
        return out

    def write(self) -> Path:
        self.paths.reports.mkdir(parents=True, exist_ok=True)
        base = self.paths.reports / self.name
        header = ["stage", "artifact", "expected", "generated", "difference", "status", "note"]
        with open(base.with_suffix(".csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f, lineterminator="\n")
            w.writerow(header)
            for r in self.rows:
                w.writerow([getattr(r, h) for h in header])
        meta = environment_summary(self.paths)
        meta.update({"report": self.name, "started": self.started, "finished": now_iso(),
                     "counts": self.counts(), "overall": FAIL if self.failed else PASS})
        with open(base.with_suffix(".json"), "w", encoding="utf-8") as f:
            json.dump({"meta": meta, "rows": [r.__dict__ for r in self.rows]}, f, indent=2)
        lines = [f"# Reproduction report: {self.name}", "",
                 f"- Overall: **{meta['overall']}**  ({_counts_text(self.counts())})",
                 f"- Image: `{meta['image_ref']}` (identity: {meta['image_status']})",
                 f"- Source fingerprint: `{meta['source_fingerprint']}`",
                 f"- Runtime: {meta['runtime']}, {meta['platform']}",
                 f"- Started {self.started}, finished {meta['finished']}", "",
                 "| Stage | Artifact | Expected | Generated | Difference | Status | Note |",
                 "|---|---|---|---|---|---|---|"]
        for r in self.rows:
            lines.append("| " + " | ".join(_md(getattr(r, h)) for h in header) + " |")
        base.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        return base.with_suffix(".md")


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.10g}"
    return "" if v is None else str(v)


def _md(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _counts_text(counts: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "no checks"


def environment_summary(paths: Paths) -> dict:
    return {
        "runtime": paths.runtime,
        "image_ref": os.environ.get("IJF_IMAGE_REF", "(none: native run)"),
        "image_status": os.environ.get("IJF_IMAGE_STATUS", "NATIVE"),
        "source_fingerprint": os.environ.get("IJF_IMAGE_FINGERPRINT")
        or os.environ.get("IJF_HOST_FINGERPRINT", "unknown"),
        "source_revision": os.environ.get("IJF_SOURCE_REVISION", "unknown"),
        "platform": f"{platform.system()} {platform.machine()}",
        "python": sys.version.split()[0],
    }


